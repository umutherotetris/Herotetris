import assert from 'node:assert/strict';
import { normalizeRoomCode, shareRoomCode } from '../js/room-share.js';

assert.equal(normalizeRoomCode('  abC789\n'),'ABC789');
assert.equal(normalizeRoomCode(' oyUN kodu: ABC789  '),'');
for(const value of [null, 'ABC123', 'ABC789Z', 'Satranç oyna ABC789','Oda kodu: ABC789Z','Oda kodu: ABC789\nOda kodu: DEF789'])assert.equal(normalizeRoomCode(value),'');
console.log('PASS strict room code validation rejects prose, invalid and ambiguous invitations');

let copy;
Object.defineProperty(globalThis,'navigator',{value:{clipboard:{writeText:async text=>{copy=text;}}},configurable:true});
globalThis.location={href:'https://example.test/Herotetris/?v=157#home'};
for(const game of ['tetris','tavla','chess']){
 assert.equal(await shareRoomCode(game,'ABC789'),'copied');
 assert.equal(normalizeRoomCode(copy),'ABC789');
 assert.ok(copy.endsWith('\nhttps://example.test/Herotetris/'));
}
assert.equal(await shareRoomCode('chess','invalid'),'unsupported');
console.log('PASS invites generated by all coded-room games can be pasted back as exact codes');
